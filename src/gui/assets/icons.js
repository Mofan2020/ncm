/** SVG namespace for createElementNS. */
const SVG_NS = 'http://www.w3.org/2000/svg';

/**
 * Build an icon element.
 *
 * @param {string} name                key in NCM_ICONS
 * @param {Object} [options]
 * @param {boolean} [options.filled]   fill the shape instead of stroking it
 * @param {number}  [options.strokeWidth]
 * @param {string}  [options.className]
 * @returns {SVGElement|null} null when the name is unknown
 */
function ncmIcon(name, options) {
    const spec = NCM_ICONS[name];
    if (!spec) return null;
    const opts = options || {};
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', '24');
    svg.setAttribute('height', '24');
    svg.setAttribute('fill', opts.filled ? 'currentColor' : 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', String(opts.strokeWidth || 2));
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    svg.setAttribute('class', opts.className || 'icon');
    spec.forEach(([tag, attrs]) => {
        const node = document.createElementNS(SVG_NS, tag);
        Object.keys(attrs).forEach((key) => node.setAttribute(key, attrs[key]));
        svg.appendChild(node);
    });
    return svg;
}

/**
 * Put an icon inside an element, replacing whatever it held.
 *
 * @param {Element} element
 * @param {string} name
 * @param {Object} [options]
 */
function setIcon(element, name, options) {
    if (!element) return;
    while (element.firstChild) element.removeChild(element.firstChild);
    const icon = ncmIcon(name, options);
    if (icon) element.appendChild(icon);
}

/**
 * Fill an element with text, or with an icon when the text is empty.
 *
 * @param {Element} element
 * @param {string} text
 * @param {string} iconName
 */
function setTextOrIcon(element, text, iconName) {
    if (!element) return;
    if (text) {
        element.textContent = text;
        return;
    }
    setIcon(element, iconName);
}

if (typeof window !== 'undefined') {
    window.NCM_ICONS = NCM_ICONS;
    window.ncmIcon = ncmIcon;
    window.setIcon = setIcon;
    window.setTextOrIcon = setTextOrIcon;
}
